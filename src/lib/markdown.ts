import type { Report } from "./schema";

const order = { P0: 0, P1: 1, P2: 2 };

/**
 * Export the COMPLETE report (all findings, endpoints, questions, tests),
 * regardless of how many are visible on screen.
 */
export function reportToMarkdown(report: Report, changeDescription?: string): string {
  const breaking = report.risks.filter((r) => r.severity === "breaking").length;
  const lines: string[] = ["# Change Impact Analysis Report", ""];
  lines.push("## Impact Summary", "");
  if (changeDescription) lines.push(`- Change analysed: ${changeDescription}`);
  lines.push(`- Affected endpoints: ${report.affectedEndpoints.length}`);
  lines.push(`- Findings: ${report.risks.length} (${breaking} breaking)`);
  lines.push(`- Open questions: ${report.openQuestions.length}`);
  lines.push(`- Suggested regression tests: ${report.testCases.length}`, "");
  const summary =
    report.impactSummary ||
    (report.risks[0]?.summary ?? report.risks[0]?.detail ?? "See findings below.");
  lines.push(summary, "");

  lines.push("## Main Findings", "");
  for (const r of report.risks) {
    lines.push(`### ${r.title} [${r.severity} · ${r.type}]`);
    lines.push(r.summary || r.detail);
    if (r.affectedEndpoints.length > 0)
      lines.push(`- Affects: ${r.affectedEndpoints.join(", ")}`);
    if (r.evidence) lines.push(`- Evidence: "${r.evidence}"`);
    lines.push("");
  }

  lines.push("## Affected Endpoints", "");
  for (const ep of report.affectedEndpoints) {
    lines.push(`- **${ep.method} ${ep.path}** (${ep.confidence}) — ${ep.reason}`);
    if (ep.evidence) lines.push(`  - Evidence: "${ep.evidence}"`);
  }

  lines.push("", "## Open Questions", "");
  for (const q of report.openQuestions) lines.push(`- ${q}`);

  lines.push("", "## Regression Test Plan (suggested, not executed)", "");
  lines.push("_Priority: P0 = breaking/auth/data-loss (run first), P1 = likely affected, P2 = edge case._", "");
  const tests = [...report.testCases].sort((a, b) => order[a.priority] - order[b.priority]);
  for (const t of tests) {
    lines.push(`### ${t.id} — ${t.title} (${t.priority})`);
    if (t.summary) lines.push(t.summary);
    lines.push(`- Covers: ${t.covers}`);
    if (t.preconditions) lines.push(`- Preconditions: ${t.preconditions}`);
    lines.push(`- Steps:`);
    t.steps.forEach((s, i) => lines.push(`  ${i + 1}. ${s}`));
    lines.push(`- Expected: ${t.expected}`);
    lines.push(`- Rationale: ${t.rationale}`, "");
  }
  lines.push("_Generated by AI Change Impact Analyzer. Findings labelled 'inferred' are unverified assumptions; tests are suggestions only._");
  return lines.join("\n");
}

export function downloadMarkdown(markdown: string) {
  const blob = new Blob([markdown], { type: "text/markdown" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "impact-report.md";
  a.click();
  URL.revokeObjectURL(url);
}
